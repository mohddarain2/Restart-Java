class Array {
    public static void main(String[] args){
        int age[] = {20,30,40,50};
        for(int i=0;i<age.length;i++){
            System.out.println(age[i]);
        }

        String Name[] = {"Darain","Faisal","Sartaj"};
        for(int i=0;i<Name.length;i++){
            System.out.println(Name[i]);
        }
    }
}

